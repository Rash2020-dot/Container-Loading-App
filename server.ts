import 'dotenv/config';
import express, { type Request, type Response } from 'express';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const PORT = Number(process.env.PORT) || 3000;
const IS_PROD = process.env.NODE_ENV === 'production';
const BREVO_API_URL = 'https://api.brevo.com/v3/smtp/email';
const EMAIL_REGEX = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

function escapeHtml(value: unknown): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function sanitizeText(value: unknown, maxLen = 200): string {
  const str = typeof value === 'string' || typeof value === 'number' ? String(value).trim() : '';
  return str.slice(0, maxLen);
}

function toNonNegativeInt(value: unknown): number {
  const num = Number(value);
  if (!Number.isFinite(num) || num < 0) return 0;
  return Math.floor(num);
}

function parseRecipients(raw: string): string[] {
  return raw
    .split(',')
    .map((entry) => entry.trim().replace(/^['"]|['"]$/g, ''))
    .filter((email) => EMAIL_REGEX.test(email));
}

function getBrevoConfig() {
  const apiKey = (process.env.BREVO_API_KEY || '').trim();
  const senderEmail = (process.env.SENDER_EMAIL || '').trim();
  const rawRecipients = (process.env.RECIPIENT_EMAILS || process.env.RECIPIENT_EMAIL || '').trim();
  const recipients = parseRecipients(rawRecipients);
  const senderName = sanitizeText(process.env.SENDER_NAME || 'Container Loading System', 80);

  const isPlaceholder =
    !apiKey ||
    !EMAIL_REGEX.test(senderEmail) ||
    recipients.length === 0 ||
    apiKey === 'your-brevo-api-key' ||
    senderEmail === 'your-sender@example.com' ||
    recipients.every((email) => email.endsWith('@example.com'));

  return {
    configured: !isPlaceholder,
    apiKey,
    senderEmail,
    recipients,
    senderName,
  };
}

async function sendBrevoEmail(subject: string, htmlContent: string) {
  const config = getBrevoConfig();
  if (!config.configured) {
    return {
      ok: false,
      skipped: true,
      message: 'Brevo email settings are not configured in environment variables yet.',
    };
  }

  const response = await fetch(BREVO_API_URL, {
    method: 'POST',
    headers: {
      accept: 'application/json',
      'content-type': 'application/json',
      'api-key': config.apiKey,
    },
    body: JSON.stringify({
      sender: {
        name: config.senderName,
        email: config.senderEmail,
      },
      to: config.recipients.map((email) => ({ email })),
      subject,
      htmlContent,
    }),
  });

  if (!response.ok) {
    console.error(`Brevo API error: HTTP ${response.status}`);
    return {
      ok: false,
      skipped: false,
      message: 'Failed to send email via Brevo. Verify BREVO_API_KEY and sender configuration.',
    };
  }

  return {
    ok: true,
    skipped: false,
    message: 'Email sent successfully via Brevo.',
  };
}

async function startServer() {
  const app = express();
  app.use(express.json({ limit: '100kb' }));

  app.get('/api/health', (_req: Request, res: Response) => {
    const config = getBrevoConfig();
    res.json({
      ok: true,
      emailConfigured: config.configured,
      recipientCount: config.recipients.length,
    });
  });

  app.post('/api/send-start-email', async (req: Request, res: Response) => {
    const containerNo = sanitizeText(req.body?.container_no, 80);
    const shipmentNo = sanitizeText(req.body?.shipment_no, 80);
    const startTime = sanitizeText(req.body?.start_time, 60);
    const totalBoxes = toNonNegativeInt(req.body?.total_boxes);

    if (!containerNo || !shipmentNo) {
      res.status(400).json({
        success: false,
        error: 'Container number and shipment number are required.',
      });
      return;
    }

    const config = getBrevoConfig();
    const htmlContent = `
      <div style="font-family: Arial, sans-serif; color: #222; line-height: 1.5; font-size: 14px;">
        <p style="color: #444;">A container loading notification has been generated by ${escapeHtml(config.senderName)}.</p>
        <hr style="border: 0; border-top: 1px dashed #ccc; margin: 15px 0;" />
        <p>Dear Team,</p>
        <p>A new container loading session has successfully started.</p>
        <p>
          Container Number : <b>${escapeHtml(containerNo)}</b><br />
          Shipment Number : <b>${escapeHtml(shipmentNo)}</b><br />
          Start Time : <b>${escapeHtml(startTime)}</b><br />
          Expected Boxes : <b>${totalBoxes}</b>
        </p>
        <p>System Status: Scanning active and in progress.</p>
        <p>Best regards,<br /><b>${escapeHtml(config.senderName)}</b></p>
      </div>
    `;

    try {
      const result = await sendBrevoEmail(
        `Container Loading Session Started - ${containerNo}`,
        htmlContent
      );
      if (result.skipped) {
        res.status(200).json({ success: false, skipped: true, message: result.message });
        return;
      }
      if (!result.ok) {
        res.status(502).json({ success: false, error: result.message });
        return;
      }
      res.status(200).json({ success: true, message: 'Start Email Sent!' });
    } catch (error) {
      console.error('Start email request failed:', error);
      res.status(500).json({
        success: false,
        error: 'Failed to contact Brevo email service.',
      });
    }
  });

  app.post('/api/send-end-email', async (req: Request, res: Response) => {
    const containerNo = sanitizeText(req.body?.container_no, 80);
    const shipmentNo = sanitizeText(req.body?.shipment_no, 80);
    const startTime = sanitizeText(req.body?.start_time, 60);
    const endTime = sanitizeText(req.body?.end_time, 60);
    const breakTime = sanitizeText(req.body?.break_time, 60);
    const processTime = sanitizeText(req.body?.process_time, 60);
    const totalTime = sanitizeText(req.body?.total_time, 60);
    const totalBoxes = toNonNegativeInt(req.body?.total_boxes);
    const scannedBoxes = toNonNegativeInt(req.body?.scanned_boxes);
    const missingBoxes = toNonNegativeInt(req.body?.missing_boxes);
    const polyBags = toNonNegativeInt(req.body?.poly_bags);
    const doubleHeightBoxes = toNonNegativeInt(req.body?.double_height_boxes);
    const longBoxes = toNonNegativeInt(req.body?.long_boxes);
    const progress = sanitizeText(req.body?.progress, 20);
    const missingListText = sanitizeText(req.body?.missing_list_text, 4000);

    if (!containerNo || !shipmentNo) {
      res.status(400).json({
        success: false,
        error: 'Container number and shipment number are required.',
      });
      return;
    }

    const config = getBrevoConfig();
    const htmlContent = `
      <div style="font-family: Arial, sans-serif; color: #222; line-height: 1.5; font-size: 14px;">
        <p style="color: #444;">Container loading summary generated by ${escapeHtml(config.senderName)}.</p>
        <hr style="border: 0; border-top: 1px dashed #ccc; margin: 15px 0;" />
        <p>Hi,</p>
        <p>Container Loading Session Completed.</p>
        <p><b>SHIPMENT DETAILS</b></p>
        <ul style="list-style-type: disc; padding-left: 20px;">
          <li>Container Number : <b>${escapeHtml(containerNo)}</b></li>
          <li>Shipment Number : <b>${escapeHtml(shipmentNo)}</b></li>
          <li>Start Time : <b>${escapeHtml(startTime)}</b></li>
          <li>End Time : <b>${escapeHtml(endTime)}</b></li>
          <li>Break Time : <b>${escapeHtml(breakTime)}</b></li>
          <li>Process Time : <b>${escapeHtml(processTime)}</b></li>
          <li>Total Time : <b>${escapeHtml(totalTime)}</b></li>
        </ul>
        <p><b>SUMMARY &amp; EXCEL DATA</b></p>
        <ul style="list-style-type: disc; padding-left: 20px;">
          <li>Total Expected Boxes (Excel) : <b>${totalBoxes}</b></li>
          <li>Successfully Scanned Boxes : <b>${scannedBoxes}</b> (${escapeHtml(progress)}%)</li>
          <li>Missing / Not Scanned Boxes : <b>${missingBoxes}</b></li>
          <li>Poly Bags : <b>${polyBags}</b> | Double Height : <b>${doubleHeightBoxes}</b> | Long Boxes : <b>${longBoxes}</b></li>
        </ul>
        ${
          missingListText
            ? `<p><b>MISSING HANDLING UNITS</b></p><pre style="background:#f8fafc;border:1px solid #e2e8f0;padding:12px;border-radius:6px;white-space:pre-wrap;font-size:12px;">${escapeHtml(missingListText)}</pre>`
            : ''
        }
      </div>
    `;

    try {
      const result = await sendBrevoEmail(
        `Container Loading Session Completed - ${containerNo}`,
        htmlContent
      );
      if (result.skipped) {
        res.status(200).json({ success: false, skipped: true, message: result.message });
        return;
      }
      if (!result.ok) {
        res.status(502).json({ success: false, error: result.message });
        return;
      }
      res.status(200).json({ success: true, message: 'End Email Sent!' });
    } catch (error) {
      console.error('End email request failed:', error);
      res.status(500).json({
        success: false,
        error: 'Failed to contact Brevo email service.',
      });
    }
  });

  if (!IS_PROD) {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.resolve(__dirname, 'dist');
    app.use(express.static(distPath));
    app.get('*', (_req: Request, res: Response) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`Container Loading Dashboard running at http://localhost:${PORT}`);
  });
}

startServer().catch((err) => {
  console.error('Failed to start server:', err);
  process.exit(1);
});
